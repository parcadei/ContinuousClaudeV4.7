#!/usr/bin/env python3
"""Capture FastEdit demo numbers from OpenRouter and write ``data.js`` for
the animated HTML page.

Usage:
    uv run --no-sync python demo/web/capture.py

Reuses the fixture picker, payload builders, and OpenRouter client from
``demo/fastedit_live.py`` — so the numbers the web page shows are the
exact numbers the terminal demo shows.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(ROOT))

from demo.fastedit_live import (  # noqa: E402
    build_fastedit_payload,
    build_native_payload,
    count_payload_tokens,
    load_fixtures,
    openrouter_client,
)


def main() -> int:
    client = openrouter_client()
    fixtures = load_fixtures()
    if not fixtures:
        print("no fixtures", file=sys.stderr)
        return 1

    print(f"capturing {len(fixtures)} fixtures via openrouter…\n")
    records: list[dict] = []
    for fx in fixtures:
        native = build_native_payload(fx)
        fe = build_fastedit_payload(fx)
        print(f"  ▸ {fx.lang:<12s}  [{fx.case_id}]")
        nt = count_payload_tokens(client, native)
        ft = count_payload_tokens(client, fe)
        pct = round((nt - ft) / nt * 100, 1) if nt else 0
        print(f"    native {nt}  →  fastedit {ft}   {pct}%")
        records.append({
            "lang": fx.lang,
            "pattern": fx.pattern,
            "case_id": fx.case_id,
            "target": fx.target_name,
            "native_payload": native,
            "fastedit_payload": fe,
            "native_tok": nt,
            "fastedit_tok": ft,
            "saved": nt - ft,
            "pct": pct,
        })

    total_native = sum(r["native_tok"] for r in records)
    total_fe = sum(r["fastedit_tok"] for r in records)
    data = {
        "model": "openai/gpt-4o-mini",
        "fixtures": records,
        "totals": {
            "native": total_native,
            "fastedit": total_fe,
            "saved": total_native - total_fe,
            "pct": round((total_native - total_fe) / total_native * 100, 1)
                   if total_native else 0,
            "ratio": round(total_native / max(total_fe, 1), 2),
            "n": len(records),
        },
    }
    out = Path(__file__).parent / "data.js"
    out.write_text(
        "// Generated by demo/web/capture.py — real OpenRouter measurements.\n"
        f"window.FASTEDIT_DATA = {json.dumps(data, indent=2)};\n"
    )
    print(f"\nwrote: {out}")
    print(f"headline: {data['totals']['pct']}% saved "
          f"(native {total_native} → fastedit {total_fe})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
